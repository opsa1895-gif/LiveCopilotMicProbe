package com.livecopilot.micprobe;

import java.util.Locale;

final class ReplyGenerator {
    static final class Replies {
        final String direct;
        final String sarcastic;
        final String funny;
        final String calm;

        Replies(String direct, String sarcastic, String funny, String calm) {
            this.direct = direct;
            this.sarcastic = sarcastic;
            this.funny = funny;
            this.calm = calm;
        }
    }

    static Replies generate(String raw) {
        String text = raw == null ? "" : raw.trim();
        String lower = text.toLowerCase(Locale.ROOT);
        if (text.isEmpty()) return new Replies("—", "—", "—", "—");

        if (containsAny(lower, "здравей", "здрасти", "hello", "hi ", "добър вечер", "добро утро")) {
            return new Replies(
                    "Здрасти! Радвам се, че си тук — как минава денят ти?",
                    "О, още един смел човек влезе в live-а — добре дошъл!",
                    "Здрасти! Влизането е безплатно, излизането вече е по желание.",
                    "Здравей и добре дошъл! Радвам се, че се включи."
            );
        }

        if (containsAny(lower, "колко струва", "цена", "колко е", "price", "струва")) {
            return new Replies(
                    "Ще ти кажа точната цена според варианта — кой точно имаш предвид?",
                    "Цената не я крия под възглавницата — кажи кой вариант гледаш.",
                    "Само да не питаш за цената на целия TikTok — кой продукт имаш предвид?",
                    "Разбира се — кажи ми кой вариант те интересува и ще уточня цената."
            );
        }

        if (containsAny(lower, "откъде си", "къде живееш", "where are you from")) {
            return new Replies(
                    "Ще ти кажа, но първо ти — откъде ме гледаш?",
                    "Локацията ми е строго секретна… освен ако не попиташ още веднъж.",
                    "От място с интернет, кафе и прекалено много TikTok.",
                    "Ще споделя общо, но лични детайли предпочитам да не казвам на live."
            );
        }

        if (containsAny(lower, "на колко си", "години си", "how old")) {
            return new Replies(
                    "Годините са само число — по-важното е колко енергия имаме днес.",
                    "Достатъчно, за да знам кога някой задава опасен въпрос.",
                    "На толкова, че рожденият ми ден вече идва прекалено бързо.",
                    "Предпочитам да не давам точна възраст на live, но благодаря за въпроса."
            );
        }

        if (containsAny(lower, "харесвам", "много си", "красив", "красива", "готин", "готина", "обичам", "love you")) {
            return new Replies(
                    "Благодаря ти, много е приятно да го чуя!",
                    "Продължавай така и ще трябва да ти дам VIP място в live-а.",
                    "Благодаря! Его-то ми току-що поиска собствен профил.",
                    "Много мило от твоя страна, благодаря ти."
            );
        }

        if (containsAny(lower, "грозен", "грозна", "тъп", "тъпа", "смешен си", "смешна си", "hate", "идиот")) {
            return new Replies(
                    "Няма проблем да не сме на едно мнение — продължаваме напред.",
                    "Толкова усилие за коментар, а можеше просто да кажеш „здрасти“.",
                    "Добре, записвам го в папката „непоискани ревюта“.",
                    "Разбирам, че не ти допада. Нека запазим разговора нормален."
            );
        }

        if (lower.contains("защо")) {
            return new Replies(
                    "Добър въпрос. Причината зависи от контекста — уточни кое точно имаш предвид.",
                    "Защото животът явно е решил да не ни дава лесните въпроси.",
                    "Защо ли? Това е моментът, в който ни трябва драматична музика.",
                    "Кажи ми кое точно имаш предвид и ще ти отговоря възможно най-точно."
            );
        }

        if (containsAny(lower, "как", "какво", "кой", "коя", "кога", "къде", "може ли", "дали", "?")) {
            String shortQuote = shorten(text, 54);
            return new Replies(
                    "За „" + shortQuote + "“ — дай ми още един детайл и ще отговоря точно.",
                    "Това е от въпросите, които идват без инструкция за употреба — дай малко контекст.",
                    "Чакай, този въпрос заслужава поне две мозъчни клетки повече — уточни го малко.",
                    "Разбрах въпроса. Уточни само един детайл, за да не ти кажа нещо неточно."
            );
        }

        String q = shorten(text, 58);
        return new Replies(
                "Разбрах те: „" + q + "“. Кажи ми още малко, за да отговоря конкретно.",
                "Смело твърдение. Сега остава само да видим дали ще издържи втори въпрос.",
                "Това прозвуча като начало на история, която ще стане интересна след 10 секунди.",
                "Разбирам какво казваш. Продължи — слушам те."
        );
    }

    private static boolean containsAny(String value, String... needles) {
        for (String n : needles) if (value.contains(n)) return true;
        return false;
    }

    private static String shorten(String s, int max) {
        String clean = s.replace('\n', ' ').trim();
        if (clean.length() <= max) return clean;
        return clean.substring(0, Math.max(1, max - 1)) + "…";
    }
}
